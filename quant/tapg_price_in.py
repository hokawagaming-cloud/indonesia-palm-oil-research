"""Focused price-in assessment around TAPG results filings (reuses existing modules).

For each results filing with an IDX timestamp (A-018 event day = first trading day the
filing was usable), compute:
  * abnormal returns vs a market model on IHSG and vs the PIT core peer index that
    EXCLUDES TAPG (estimation window: 250 trading days ending 11 days before the event)
  * cumulative abnormal returns (CAR) for [0,0], [0,+1], [0,+5], [0,+10] and to the last date
  * abnormal volume = volume / mean volume over days -60..-11
Price or volume moves alone are NOT treated as evidence of mispricing.

Output: data/reference/research/TAPG_event_study.csv; research/company/TAPG/price_in_assessment.md
Usage:  python -I -X utf8 quant/tapg_price_in.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from tapg_quant_research import adj, peer_index  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
REF = ROOT / "data" / "reference"
EVENTS = ["FY2024", "Q1 2025", "H1 2025", "9M 2025", "FY2025", "Q1 2026", "H1 2026", "9M 2026"]


def main() -> int:
    raw = pd.read_csv(ROOT / "data" / "raw" / "ohlcv" / "TAPG.csv", index_col=0, parse_dates=True).apply(pd.to_numeric, errors="coerce")
    r = pd.DataFrame({"tapg": adj("TAPG").pct_change(), "ihsg": adj("IHSG").pct_change(), "peers": peer_index()}).dropna(subset=["tapg"]).fillna(0)
    vol = raw["Volume"].reindex(r.index)
    dd = pd.read_csv(REF / "TAPG_disclosure_dates.csv")
    dd = dd[dd.disclosure.isin(["interim FS", "audited FS"]) & dd.period.isin(EVENTS)]
    rows = []
    for _, e in dd.iterrows():
        t0 = pd.Timestamp(e.available_from)
        if t0 not in r.index:
            t0 = r.index[r.index.searchsorted(t0)]
        i0 = r.index.get_loc(t0)
        est = r.iloc[max(0, i0 - 260):i0 - 10]
        out = {"event": e.period, "idx_timestamp": e.idx_timestamp_wib, "event_day": t0.date()}
        for bench in ("ihsg", "peers"):
            X = np.column_stack([np.ones(len(est)), est[bench]])
            b, *_ = np.linalg.lstsq(X, est.tapg, rcond=None)
            sd = float(np.std(est.tapg - X @ b, ddof=2))
            ar = r.tapg - (b[0] + b[1] * r[bench])
            for lab, k in (("0_0", 0), ("0_1", 1), ("0_5", 5), ("0_10", 10)):
                w = ar.iloc[i0:i0 + k + 1]
                out[f"car_{bench}_{lab}"] = w.sum()
                out[f"t_{bench}_{lab}"] = w.sum() / (sd * np.sqrt(len(w)))
            out[f"car_{bench}_to_last"] = ar.iloc[i0:].sum() if e.period == "9M 2026" else np.nan
            out[f"beta_{bench}"] = b[1]
        base_vol = vol.iloc[max(0, i0 - 60):i0 - 10].mean()
        out["abn_volume_day0"] = vol.iloc[i0] / base_vol
        out["abn_volume_0_5"] = vol.iloc[i0:i0 + 6].mean() / base_vol
        out["raw_ret_0_5"] = (1 + r.tapg.iloc[i0:i0 + 6]).prod() - 1
        rows.append(out)
    E = pd.DataFrame(rows)
    E.to_csv(REF / "research" / "TAPG_event_study.csv", index=False, float_format="%.4f")

    last = r.index[-1]
    i9 = r.index.get_loc(pd.Timestamp(E[E.event == "9M 2026"].event_day.iloc[0]))
    since = (1 + r.iloc[i9:]).prod() - 1
    px_last = adj("TAPG").iloc[-1]
    exp = pd.read_csv(REF / "TAPG_expectations_snapshots.csv")
    cons = exp[(exp.source.str.startswith("Yahoo")) & (exp.as_of == "2026-11-24")].set_index("metric")["value"]
    rm = pd.read_csv(REF / "research" / "TAPG_residual_momentum.csv", index_col=0).iloc[:, 0]
    md = ["# TAPG — Price-in Assessment (focused)", "",
          "_Generated by `quant/tapg_price_in.py`. Event day = first trading day a filing was usable (IDX timestamp, A-018). Peer index = PIT core names excluding TAPG. Returns and volume are evidence about what the market did, not about whether it was right._", "",
          "## Results-filing event study (CAR = cumulative abnormal return; t = CAR / (σ√n))", "",
          "| Event | Event day | CAR vs IHSG [0,1] | t | CAR vs peers [0,1] | t | CAR vs peers [0,5] | t | Abn. volume day 0 | Raw return [0,5] |", "|---|---|---|---|---|---|---|---|---|---|"]
    for _, x in E.iterrows():
        md.append(f"| {x.event} | {x.event_day} | {x.car_ihsg_0_1:+.1%} | {x.t_ihsg_0_1:.1f} | {x.car_peers_0_1:+.1%} | {x.t_peers_0_1:.1f} | {x.car_peers_0_5:+.1%} | {x.t_peers_0_5:.1f} | {x.abn_volume_day0:.1f}× | {x.raw_ret_0_5:+.1%} |")
    e9 = E[E.event == "9M 2026"].iloc[0]
    md += ["", f"**9M 2026 (beat: 9M profit 85% of FY consensus).** From the event day {e9.event_day} to {last.date()}:",
           f"- TAPG {since.tapg:+.1%}, IHSG {since.ihsg:+.1%}, peers ex-TAPG {since.peers:+.1%}.",
           f"- CAR vs IHSG {e9.car_ihsg_to_last:+.1%}; CAR vs peers {e9.car_peers_to_last:+.1%}.",
           "",
           "## Expectations and valuation snapshot (Yahoo consensus retrieved 2026-11-24; reported-EPS basis)", "",
           f"- **Price:** TAPG IDR {px_last:,.0f}, so forward P/E is {px_last/cons['FY26 EPS']:.1f}× FY26 consensus EPS ({cons['FY26 EPS']:.1f}) and {px_last/cons['FY27 EPS']:.1f}× FY27 ({cons['FY27 EPS']:.1f}).",
           "- **Revisions:** FY26 EPS consensus moved 215.5 (90 and 60 days ago, i.e. late Aug/Sep) → 208.1 (30 days ago = 25 Oct, BEFORE the 28 Oct results; unchanged at 7 days ago) → 212.9 (now; one upward revision in the last 7 days, i.e. after the results). FY27 moved 212.1 → 219.8 → 225.3.",
           f"- **Implied Q4 2026 profit:** about {cons['FY26 EPS']*19852.54/1000 - 3505.62:,.0f}bn from current consensus, against our exploratory base case of about 1,268bn and Q4 2025 of 1,023bn (see `q4_2026_nowcast.md`).",
           f"- **Residual momentum:** TAPG residual-momentum score {rm.iloc[-1]:+.2f} (last month-end; the cross-sectional IC is noise-level, see `quant_prelim_results.md`).", "",
           "## Reading (no mispricing claim)", "",
           "- **No immediate reaction** to the 9M beat: [0,+1] abnormal return was about 0 vs IHSG and peers, and day-0 volume was 0.7× normal (not elevated).",
           "- **The underperformance came afterwards:** −13% vs IHSG and −15% vs peers by 24 Nov, with no TAPG results filing in between. Its cause is not identified (candidates: the earnings-call message on Q4 fertiliser and 2027 El Niño/fertiliser guidance, flows, sector rotation).",
           "- **Consensus:** analysts cut FY26 before the results. After the results, one analyst raised it.",
           "- Consensus still implies a Q4 (~720bn) well below Q4 2025 (1,023bn) and below our exploratory range (882–1,651bn).",
           "- This gap is the testable expectations question.",
           "- **It is not a mispricing finding.**",
           "  - The negative reaction may reflect information we lack: the earnings call (fertiliser catch-up guidance, 2027 El Niño and fertiliser +25% guidance) or sector rotation.",
           "  - The scenario model is unvalidated.",
           "  - Consensus covers only 4 analysts.",
           "  - The FY2026 results will not be filed until about March 2027.",
           "- **Data limits:**",
           "  - Yahoo prices are unofficial (S-002).",
           "  - The 7- and 30-day consensus columns are as displayed on 2026-11-24 and could not be archived independently."]
    (ROOT / "research" / "company" / "TAPG" / "price_in_assessment.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
