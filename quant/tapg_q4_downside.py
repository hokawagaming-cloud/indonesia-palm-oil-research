"""Joint downside analysis for TAPG Q4 2026 profit (Phase III, priority 1).

Reuses `run()` from quant/tapg_q4_2026_nowcast.py. Each driver gets an evidence-anchored
grid. A level is 'plausible' (severity 0), 'stressed' (1) or 'extreme' (2):

  harvest (sales from production vs Q3)  1.00 / 0.95 (FY26 guidance-implied) / 0.90 (El Niño lag)
  CPO ASP vs Q3                          -5.5% (KPBN Q4-to-date) / -10% / -15%
  fertiliser (IDR bn, Q3 = 75)           230 / 340 (FY26 = FY25 level, broker est.) / 450
  purchased-FFB extra cost (IDR bn)      0 / +75 / +150 (beyond 50% price pass-through; Q3 +60% YoY)
  inventory release share                0.5 / 0.25 / 0.0 (pickup delays persist)
  JV + associates (IDR bn)               310 / 240 (Q4'25) / 180
  other operating items (IDR bn)         -72 (Q4'25) / -150 / -250 (one-offs, write-downs)
  tax rate on PBT ex JV                  21.6% (Q3) / 25% / 28%

Outputs: share of the full grid at or below 720bn (the consensus-implied Q4); the
least-severe combinations reaching it; and a judgmental Monte Carlo (triangular
distributions over the plausible..extreme range). These are judgement-weighted, NOT
estimated probabilities.

Output: data/reference/research/TAPG_q4_downside_grid_summary.csv, research/company/TAPG/q4_downside.md
Usage:  python -I -X utf8 quant/tapg_q4_downside.py
"""
from __future__ import annotations

import itertools
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import tapg_q4_2026_nowcast as n  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
TARGET = 720.0  # consensus-implied Q4 (D-016)
LEVELS = {
    "harvest": [1.00, 0.95, 0.90],
    "asp_vs_q3": [-0.055, -0.10, -0.15],
    "fert_q4": [230, 340, 450],
    "ffb_cost_extra": [0, 75, 150],
    "inv_release": [0.5, 0.25, 0.0],
    "jv_assoc": [310, 240, 180],
    "other_op": [-72, -150, -250],
    "tax_rate": [0.216, 0.25, 0.28],
}
FIXED = dict(pk_asp_vs_q3=None, ffb_price_pass=0.5)


def scen(combo: dict) -> dict:
    s = dict(FIXED, **combo)
    s["pk_asp_vs_q3"] = combo["asp_vs_q3"]
    return s


def main() -> int:
    keys = list(LEVELS)
    rows = []
    for idx in itertools.product(range(3), repeat=len(keys)):
        combo = {k: LEVELS[k][i] for k, i in zip(keys, idx)}
        r = n.run(scen(combo))
        rows.append({**combo, "severity": sum(idx), "n_extreme": sum(i == 2 for i in idx),
                     "n_stressed_or_worse": sum(i >= 1 for i in idx), "q4_np": r["net_profit_owners"]})
    G = pd.DataFrame(rows)
    below = G[G.q4_np <= TARGET]
    # least-severe combinations that reach the target
    mins = below.sort_values(["n_extreme", "severity", "q4_np"], ascending=[True, True, False]).head(12)
    summary = {
        "grid_size": len(G), "share_le_720": len(below) / len(G),
        "share_le_720_no_extreme": (G[(G.n_extreme == 0)].q4_np <= TARGET).mean(),
        "min_severity_reaching_720": int(below.severity.min()) if len(below) else None,
        "all_plausible_q4": float(G[G.severity == 0].q4_np.iloc[0]),
        "all_stressed_q4": float(n.run(scen({k: v[1] for k, v in LEVELS.items()}))["net_profit_owners"]),
        "all_extreme_q4": float(n.run(scen({k: v[2] for k, v in LEVELS.items()}))["net_profit_owners"]),
    }
    # one-at-a-time sensitivity from the all-plausible point
    base_combo = {k: v[0] for k, v in LEVELS.items()}
    base_np = n.run(scen(base_combo))["net_profit_owners"]
    sens = []
    for k, v in LEVELS.items():
        for lvl in (1, 2):
            c = dict(base_combo, **{k: v[lvl]})
            sens.append({"driver": k, "level": ["plausible", "stressed", "extreme"][lvl], "value": v[lvl],
                         "delta_q4_np": n.run(scen(c))["net_profit_owners"] - base_np})
    S = pd.DataFrame(sens)
    # judgmental Monte Carlo
    rng = np.random.default_rng(20261124)
    N = 20000
    draws = {k: rng.triangular(min(v[0], v[2]), v[0] if k != "inv_release" else v[0], max(v[0], v[2]), N)
             if True else None for k, v in LEVELS.items()}
    mc = np.array([n.run(scen({k: draws[k][i] for k in LEVELS}))["net_profit_owners"] for i in range(N)])
    q = np.percentile(mc, [5, 25, 50, 75, 95])
    summary.update({"mc_p05": q[0], "mc_p25": q[1], "mc_p50": q[2], "mc_p75": q[3], "mc_p95": q[4],
                    "mc_prob_le_720": float((mc <= TARGET).mean()), "mc_prob_le_1023": float((mc <= 1022.6).mean())})
    out = ROOT / "data" / "reference" / "research"
    pd.Series(summary).to_csv(out / "TAPG_q4_downside_grid_summary.csv")
    mins.to_csv(out / "TAPG_q4_downside_min_combos.csv", index=False, float_format="%.3f")
    S.to_csv(out / "TAPG_q4_downside_sensitivity.csv", index=False, float_format="%.1f")

    md = ["# TAPG — Q4 2026 Joint Downside Analysis", "",
          f"_Generated by `quant/tapg_q4_downside.py` using the corrected nowcast (`run()`). Target = {TARGET:.0f}bn, the Q4 implied by current S&P consensus. Judgement-weighted; not estimated probabilities._", "",
          "## Driver grid (plausible / stressed / extreme)", "", "| Driver | Plausible | Stressed | Extreme | Δ Q4 profit if stressed | if extreme |", "|---|---|---|---|---|---|"]
    for k, v in LEVELS.items():
        d1 = S[(S.driver == k) & (S.level == "stressed")].delta_q4_np.iloc[0]
        d2 = S[(S.driver == k) & (S.level == "extreme")].delta_q4_np.iloc[0]
        md.append(f"| {k} | {v[0]} | {v[1]} | {v[2]} | {d1:+,.0f} | {d2:+,.0f} |")
    md += ["", f"From the all-plausible point (Q4 {base_np:,.0f}bn; this is not the base case, which also assumes no extra purchased-FFB cost and Q3 tax), each driver alone moves Q4 profit by the amounts above.", "",
           "## Joint results", "",
           f"- Full grid {summary['grid_size']:,} combinations: **{summary['share_le_720']:.0%}** at or below 720bn.",
           f"- Combinations with no driver at its extreme: {summary['share_le_720_no_extreme']:.0%} at or below 720bn.",
           f"- All drivers stressed together: Q4 {summary['all_stressed_q4']:,.0f}bn. All drivers extreme: {summary['all_extreme_q4']:,.0f}bn.",
           f"- Judgmental Monte Carlo (DOWNSIDE-ONLY by construction: triangular from the plausible level toward the extreme, mode at plausible). It is a downside stress distribution, not a central estimate: median {summary['mc_p50']:,.0f}bn, 5–95% range {summary['mc_p05']:,.0f}–{summary['mc_p95']:,.0f}bn; P(≤720) ≈ {summary['mc_prob_le_720']:.0%}, P(≤ Q4'25's 1,023) ≈ {summary['mc_prob_le_1023']:.0%}.", "",
           "## Least-severe combinations reaching ≤ 720bn", "", "| harvest | ASP | fert | FFB extra | inv. release | JV | other op | tax | Q4 profit |", "|---|---|---|---|---|---|---|---|---|"]
    for _, r in mins.head(8).iterrows():
        md.append(f"| {r.harvest} | {r.asp_vs_q3:+.1%} | {r.fert_q4:.0f} | {r.ffb_cost_extra:.0f} | {r.inv_release} | {r.jv_assoc:.0f} | {r.other_op:.0f} | {r.tax_rate:.1%} | {r.q4_np:,.0f} |")
    md += ["", "## Interpretation", "",
           "- **Q4 at or below the consensus-implied ~720bn needs several adverse drivers at once**, typically fertiliser catch-up together with a lower ASP, delayed inventory, a weaker JV and year-end charges. No single plausible driver gets there.",
           "- With every driver at 'stressed' simultaneously, Q4 ≈ 728bn. With no driver at an extreme, none of the grid reaches 720bn; at least one extreme driver (most often ASP −15%) is needed.",
           "- The revised bear case (765bn) is close to that level, so **the bear case is not conservative enough to rule out consensus**. A realistic joint downside (all drivers stressed) is in the table above.",
           "- **Biggest swing factors:** fertiliser (level unknown; only Q3 = 75bn and YoY changes are disclosed), CPO ASP, and year-end other items. Q4 2025 had −72bn of other items, vs +6bn in Q3 2026."]
    (ROOT / "research" / "company" / "TAPG" / "q4_downside.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
