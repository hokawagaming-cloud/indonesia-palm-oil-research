"""Preliminary quantitative research on TAPG (descriptive; NOT a trading signal or rating).

Analyses
  1. Relative performance: TAPG vs IHSG and vs an equal-weight peer index (PIT core
     liquidity names EXCLUDING TAPG), by calendar year and cumulatively.
  2. Rolling market regression: 252-day OLS of TAPG daily excess-of-nothing returns on
     IHSG (beta, alpha, R^2), plus a 2-factor version adding the peer index.
  3. Monthly CPO sensitivity: TAPG monthly log return on the change in World Bank palm oil
     price (USD), change in USD/IDR, and the IHSG return; Newey-West t-stats.
  4. Residual momentum: 12-1 month cumulative residual return from a 36-month rolling
     market model (min 24 obs), for TAPG and the PIT core universe, plus a descriptive
     cross-sectional rank correlation with next-month returns.
  5. Drawdowns for TAPG, IHSG and the peer index.
  6. Lead-lag: correlations of TAPG monthly returns (raw and vs IHSG) with CPO and FX
     changes at lags -3..+3, plus a regression on lagged drivers.

Caveats printed with the results: short sample (TAPG listed 2021-04), the World Bank
price is a monthly AVERAGE (mechanically lags month-end prices), Yahoo data are
unofficial (S-002), and associations are not causal.

Outputs: data/reference/research/TAPG_*.csv and research/company/TAPG/quant_prelim_results.md
Usage:   python -I quant/tapg_quant_research.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from stats_utils import drawdowns, lagged_corr, ols_nw

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw" / "ohlcv"
REF = ROOT / "data" / "reference"
OUT = REF / "research"
OUT.mkdir(parents=True, exist_ok=True)


def adj(t: str) -> pd.Series:
    df = pd.read_csv(RAW / f"{t}.csv", index_col=0, parse_dates=True)
    s = pd.to_numeric(df["Adj Close"], errors="coerce").dropna()
    return s[~s.index.duplicated()]


def peer_index(exclude: str = "TAPG") -> pd.Series:
    """Equal-weight daily returns of PIT core-liquidity names excluding `exclude`."""
    from benchmarks import ew_buy_and_hold
    pit = pd.read_csv(REF / "pit_universe_monthly.csv", parse_dates=["date"])
    core = pit[(pit.liquidity_band == "core_liquidity") & (pit.ticker != exclude)]
    members = {d: list(g.ticker) for d, g in core.groupby("date")}
    px = pd.concat({t: adj(t) for t in sorted(core.ticker.unique())}, axis=1).sort_index()
    return ew_buy_and_hold(px.pct_change(fill_method=None), members).rename("peers_ew")


def main() -> int:
    md = ["# TAPG — Preliminary Quantitative Research", "",
          "_Generated by `quant/tapg_quant_research.py`. Descriptive statistics only: associations are not causal, nothing here is a trading signal, and no rating is implied._", ""]
    tapg = adj("TAPG").pct_change().rename("tapg")
    ihsg = adj("IHSG").pct_change().rename("ihsg")
    peers = peer_index()
    d = pd.concat([tapg, ihsg, peers], axis=1).loc["2021-04-13":].dropna(subset=["tapg"])
    d = d.fillna(0.0)
    d.to_csv(OUT / "TAPG_daily_returns.csv", float_format="%.6f")

    # 1. relative performance ---------------------------------------------------------
    yr = (1 + d).groupby(d.index.year).prod() - 1
    yr["tapg_minus_ihsg"] = yr.tapg - yr.ihsg
    yr["tapg_minus_peers"] = yr.tapg - yr.peers_ew
    cum = (1 + d).prod() - 1
    yr.to_csv(OUT / "TAPG_relative_performance_yearly.csv", float_format="%.4f")
    md += ["## 1. Relative performance (total return; IHSG is a price index)", "",
           f"Sample {d.index[0].date()} to {d.index[-1].date()}. Cumulative: TAPG {cum.tapg:+.1%}, IHSG {cum.ihsg:+.1%}, peers EW (PIT core ex-TAPG) {cum.peers_ew:+.1%}.", "",
           "| Year | TAPG | IHSG | Peers EW | TAPG − IHSG | TAPG − peers |", "|---|---|---|---|---|---|"]
    md += [f"| {y} | {r.tapg:+.1%} | {r.ihsg:+.1%} | {r.peers_ew:+.1%} | {r.tapg_minus_ihsg:+.1%} | {r.tapg_minus_peers:+.1%} |" for y, r in yr.iterrows()]
    md += ["", "Partial years: 2021 runs from the listing date; 2026 is year-to-date.", ""]

    # 2. rolling market regression ----------------------------------------------------
    W = 252
    roll = []
    for i in range(W, len(d) + 1, 5):
        w = d.iloc[i - W:i]
        X1 = np.column_stack([np.ones(W), w.ihsg])
        b1, res1, *_ = np.linalg.lstsq(X1, w.tapg, rcond=None)
        r2_1 = 1 - ((w.tapg - X1 @ b1) ** 2).sum() / ((w.tapg - w.tapg.mean()) ** 2).sum()
        X2 = np.column_stack([np.ones(W), w.ihsg, w.peers_ew])
        b2, *_ = np.linalg.lstsq(X2, w.tapg, rcond=None)
        r2_2 = 1 - ((w.tapg - X2 @ b2) ** 2).sum() / ((w.tapg - w.tapg.mean()) ** 2).sum()
        roll.append({"date": w.index[-1].date(), "beta_ihsg": b1[1], "alpha_daily": b1[0], "r2_ihsg": r2_1,
                     "beta_ihsg_2f": b2[1], "beta_peers_2f": b2[2], "r2_2f": r2_2})
    roll = pd.DataFrame(roll)
    roll.to_csv(OUT / "TAPG_rolling_beta.csv", index=False, float_format="%.4f")
    full = ols_nw(d.tapg, d[["ihsg"]], lags=5)
    full2 = ols_nw(d.tapg, d[["ihsg", "peers_ew"]], lags=5)
    md += ["## 2. Market factor regression (daily)", "",
           f"Full sample, one factor: beta {full.loc['ihsg','coef']:.2f} (NW t {full.loc['ihsg','t_nw']:.1f}), R² {full.attrs['r2']:.2f}, n={full.attrs['nobs']}.",
           f"Two factors: IHSG beta {full2.loc['ihsg','coef']:.2f} (t {full2.loc['ihsg','t_nw']:.1f}), peer beta {full2.loc['peers_ew','coef']:.2f} (t {full2.loc['peers_ew','t_nw']:.1f}), R² {full2.attrs['r2']:.2f}.",
           f"Rolling 252-day IHSG beta: min {roll.beta_ihsg.min():.2f}, median {roll.beta_ihsg.median():.2f}, max {roll.beta_ihsg.max():.2f}; latest {roll.beta_ihsg.iloc[-1]:.2f} (R² {roll.r2_ihsg.iloc[-1]:.2f}).",
           "Low R² against IHSG means index exposure explains little of TAPG's daily variance; the sector (peer) factor explains more.", ""]

    # 3. monthly CPO sensitivity ------------------------------------------------------
    mac = pd.read_csv(REF / "macro_monthly.csv", index_col=0)
    mac.index = pd.PeriodIndex(mac.index, freq="M")
    m = (1 + d).groupby(d.index.to_period("M")).prod() - 1
    m = np.log1p(m)
    m = m.iloc[1:]  # drop the partial listing month
    m = m[m.index <= mac["palm_oil_usd_t"].last_valid_index()]
    drv = pd.DataFrame({"d_ln_cpo_usd": np.log(mac.palm_oil_usd_t).diff(),
                        "d_ln_usdidr": np.log(mac.usdidr_month_avg).diff(),
                        "d_ln_cpo_idr": np.log(mac.palm_oil_idr_kg).diff(),
                        "d_ln_brent": np.log(mac.brent_usd_bbl).diff(),
                        "d_ln_soy": np.log(mac.soybean_oil_usd_t).diff()})
    mm = m.join(drv, how="inner")
    mm.to_csv(OUT / "TAPG_monthly_panel.csv", float_format="%.6f")
    reg = ols_nw(mm.tapg, mm[["d_ln_cpo_usd", "d_ln_usdidr", "ihsg"]], lags=3)
    reg_x = ols_nw(mm.tapg - mm.ihsg, mm[["d_ln_cpo_idr"]], lags=3)
    reg.to_csv(OUT / "TAPG_cpo_sensitivity.csv")
    md += ["## 3. Monthly CPO sensitivity (log returns; Newey-West, 3 lags)", "",
           f"n = {reg.attrs['nobs']} months ({mm.index[0]} to {mm.index[-1]}), R² {reg.attrs['r2']:.2f}.", "",
           "| Regressor | coef | NW t |", "|---|---|---|"]
    md += [f"| {k} | {r.coef:.2f} | {r.t_nw:.2f} |" for k, r in reg.iterrows()]
    md += ["", f"TAPG return minus IHSG on Δln CPO (IDR): coef {reg_x.loc['d_ln_cpo_idr','coef']:.2f}, NW t {reg_x.loc['d_ln_cpo_idr','t_nw']:.2f}, R² {reg_x.attrs['r2']:.2f}.",
           "The CPO series is a monthly average (S-003), which dampens and delays its contemporaneous link to month-end equity returns. Coefficients are associations over a short, regime-specific sample.", ""]

    # 4. residual momentum ------------------------------------------------------------
    pit = pd.read_csv(REF / "pit_universe_monthly.csv", parse_dates=["date"])
    names = sorted(pit[pit.liquidity_band == "core_liquidity"].ticker.unique())
    px = pd.concat({t: adj(t) for t in names + ["IHSG"]}, axis=1).sort_index()
    mret = px.resample("ME").last().pct_change(fill_method=None)
    resid = pd.DataFrame(index=mret.index, columns=names, dtype=float)
    for t in names:
        for i in range(len(mret)):
            win = mret.iloc[max(0, i - 36):i][[t, "IHSG"]].dropna()
            if len(win) >= 24 and pd.notna(mret[t].iloc[i]) and pd.notna(mret["IHSG"].iloc[i]):
                X = np.column_stack([np.ones(len(win)), win.IHSG])
                b, *_ = np.linalg.lstsq(X, win[t], rcond=None)
                resid.iloc[i, resid.columns.get_loc(t)] = mret[t].iloc[i] - (b[0] + b[1] * mret["IHSG"].iloc[i])
    score = resid.shift(1).rolling(11, min_periods=9).sum()  # months t-12..t-2 (skip most recent)
    sd = resid.shift(1).rolling(11, min_periods=9).std()
    score = score / sd  # residual-momentum t-score style scaling
    elig = pit[pit.liquidity_band == "core_liquidity"].assign(month=lambda x: x.date.dt.to_period("M"))
    ics = []
    for mth, g in elig.groupby("month"):
        idx = score.index[score.index.to_period("M") == mth]
        if not len(idx):
            continue
        i = score.index.get_loc(idx[0])
        if i + 1 >= len(score):
            continue
        s = score.iloc[i][g.ticker].dropna()
        f = mret.iloc[i + 1][s.index].dropna()
        s = s[f.index]
        if len(s) >= 5:
            ics.append({"month": str(mth), "n": len(s), "rank_ic": s.rank().corr(f.rank())})
    ics = pd.DataFrame(ics)
    ics.to_csv(OUT / "residual_momentum_ic.csv", index=False, float_format="%.4f")
    tapg_rm = score["TAPG"].dropna()
    pd.DataFrame({"tapg_resid_mom_score": tapg_rm}).to_csv(OUT / "TAPG_residual_momentum.csv", float_format="%.4f")
    ic_mean, ic_t = ics.rank_ic.mean(), ics.rank_ic.mean() / (ics.rank_ic.std() / np.sqrt(len(ics)))
    md += ["## 4. Residual momentum (36-month market model; 12-1 month residual t-score)", "",
           f"TAPG score available from {tapg_rm.index[0].date()} (needs 24 months of history). Latest {tapg_rm.iloc[-1]:+.2f} at {tapg_rm.index[-1].date()}.",
           f"Cross-sectional rank IC with next-month returns across PIT core names: mean {ic_mean:+.3f}, t {ic_t:.2f}, over {len(ics)} months with an average of {ics.n.mean():.1f} names.",
           "With roughly 6–12 names per month, the IC is very noisy. This is a diagnostic, not evidence of a usable factor.", ""]

    # 5. drawdowns --------------------------------------------------------------------
    md += ["## 5. Drawdowns (daily total-return levels)", "", "| Series | Max drawdown | Peak | Trough | Recovered |", "|---|---|---|---|---|"]
    ddall = []
    for c in ["tapg", "ihsg", "peers_ew"]:
        dd = drawdowns((1 + d[c]).cumprod())
        dd.insert(0, "series", c)
        ddall.append(dd.head(5))
        r = dd.iloc[0]
        md.append(f"| {c} | {r.depth:.1%} | {r.peak.date()} | {r.trough.date()} | {'no' if pd.isna(r.recovery) else r.recovery.date()} |")
    pd.concat(ddall).to_csv(OUT / "TAPG_drawdowns.csv", index=False)
    md.append("")

    # 6. lead-lag ---------------------------------------------------------------------
    ll = []
    for drv_name in ["d_ln_cpo_usd", "d_ln_cpo_idr", "d_ln_usdidr", "d_ln_brent"]:
        for tgt, y in [("tapg", mm.tapg), ("tapg_minus_ihsg", mm.tapg - mm.ihsg)]:
            t = lagged_corr(mm[drv_name], y)
            t.insert(0, "target", tgt); t.insert(0, "driver", drv_name)
            ll.append(t)
    ll = pd.concat(ll)
    ll.to_csv(OUT / "TAPG_lead_lag.csv", index=False, float_format="%.4f")
    lagX = pd.DataFrame({f"cpo_idr_l{k}": mm.d_ln_cpo_idr.shift(k) for k in (0, 1, 2)} |
                        {f"usdidr_l{k}": mm.d_ln_usdidr.shift(k) for k in (0, 1)})
    lr = ols_nw(mm.tapg - mm.ihsg, lagX, lags=3)
    lr.to_csv(OUT / "TAPG_lead_lag_regression.csv")
    sig = ll[(ll["corr"].abs() > 2 * ll["approx_se"])]
    md += ["## 6. Commodity and currency lead-lag (monthly)", "",
           "Positive k means the driver leads TAPG by k months. Approximate ±2 s.e. band is ±2/√n.", "",
           "| Driver | Target | k=-1 | k=0 | k=+1 | k=+2 | k=+3 |", "|---|---|---|---|---|---|---|"]
    for (dn, tg), g in ll.groupby(["driver", "target"]):
        gg = g.set_index("lag_k")["corr"]
        md.append(f"| {dn} | {tg} | {gg[-1]:+.2f} | {gg[0]:+.2f} | {gg[1]:+.2f} | {gg[2]:+.2f} | {gg[3]:+.2f} |")
    md += ["", f"Correlations outside ±2 s.e.: {len(sig)} of {len(ll)} (about {0.05*len(ll):.0f} expected by chance at 5%).",
           f"Regression of TAPG−IHSG on CPO(IDR) lags 0–2 and USD/IDR lags 0–1: R² {lr.attrs['r2']:.2f}, n={lr.attrs['nobs']}; coefficients in `TAPG_lead_lag_regression.csv`.",
           "Any apparent CPO lead at k=+1 is partly mechanical: a monthly-average price for month t−1 overlaps equity returns that already reacted to daily prices within month t−1.", ""]

    md += ["## Data and caveats", "",
           "- Prices: Yahoo Finance adjusted closes (S-002, unofficial; cross-check pending). IHSG is a price index, while TAPG and the peers are total return, so TAPG − IHSG is overstated by IHSG's dividend yield.",
           "- Peers: equal-weight PIT core-liquidity names excluding TAPG, rebalanced monthly (D-003/D-004 tiers not applied; liquidity band only).",
           "- CPO: World Bank Pink Sheet monthly average (S-003); USD/IDR is the monthly average of Yahoo IDR=X.",
           "- Sample: TAPG since its April 2021 listing, about 5.5 years. Commodity-cycle and policy regimes (export bans in 2022, levy changes) dominate. There are no out-of-sample tests."]
    (ROOT / "research" / "company" / "TAPG" / "quant_prelim_results.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
