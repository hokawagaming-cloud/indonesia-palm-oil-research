"""Phase IV: (a) does a TAPG earnings beat produce a tradable reaction? (b) attractive entry range.

(a) Uses the 8 results events already in data/reference/research/TAPG_event_study.csv.
    The surprise proxy is YoY growth in profit to owners of the reported cumulative period
    (OBS, from filings/press). No point-in-time consensus history exists, so a true
    consensus surprise is unavailable except 9M26 (beat: 85% of FY consensus). n = 8.
(b) Probability-weighted 12-month value from valuation/reverse_valuation.implied_e
    inverted: V = E x conversion x (1+g)/(ke-g)/shares, plus 12 months of dividends.
    Scenario earnings and probabilities are EST (A-028). Entry price = price at which the
    expected 12-month total return >= hurdle (ke + 5pp margin of safety = 17.5%).

Usage: python -I -X utf8 valuation/tapg_entry_and_tactical.py
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
REF = ROOT / "data" / "reference"
SHARES = 19852.54
PRICE = 1710.0
KE, G, CONV = 0.125, 0.02, 0.85
HURDLE = KE + 0.05
# Forward dividend capacity (Phase V; replaces trailing-yield dividends, D-024):
# next-12m dividend = FY26 final (payout x FY26 EPS - FY26 interims already paid, IDR 130 = 60 + 70)
#                   + FY27 interims (interim share x payout x FY27 EPS)
PAYOUT = 0.85            # EST: KBV FY26F assumption; FY25 cash dividends 3,276bn vs FY24 NP 3,120bn (105%)
FY26_INTERIMS_PAID = 130.0  # OBS: Aug 2026 IDR 60 + Nov 2026 IDR 70 (S-020/S-044)
INTERIM_SHARE = FY26_INTERIMS_PAID / (PAYOUT * 4714.7 * 1000 / 19852.54)  # DER ~0.64 of the annual payout


def fwd_dividend(fy26_np: float, fy27_np: float) -> float:
    eps26, eps27 = fy26_np * 1000 / 19852.54, fy27_np * 1000 / 19852.54
    return max(PAYOUT * eps26 - FY26_INTERIMS_PAID, 0.0) + INTERIM_SHARE * PAYOUT * eps27


# (label, sustainable profit IDR bn, probability, 12m dividend IDR/share from forward capacity)
SCEN = [("bear: mean reversion to FY2023-25 average", 2810.0, 0.30, fwd_dividend(4270.4, 3638.0)),
        ("base: our FY27 base", 4062.0, 0.50, fwd_dividend(4714.7, 4062.0)),
        ("bull: our FY27 bull", 4969.0, 0.20, fwd_dividend(5157.1, 4969.0))]
# YoY growth of profit to owners in each reported cumulative period (OBS: filings / press S-026)
SURPRISE_PROXY = {"FY2024": 0.940, "Q1 2025": 805.3 / 370.8 - 1, "H1 2025": 0.753, "9M 2025": 0.6567,
                  "FY2025": 3702.3 / 3120.3 - 1, "Q1 2026": 739.8 / 805.3 - 1, "H1 2026": 2040.4 / 1694.1 - 1,
                  "9M 2026": 3505.6 / 2679.6 - 1}


def value_per_share(e: float) -> float:
    return e * CONV * (1 + G) / (KE - G) / SHARES * 1000


def main() -> int:
    ev = pd.read_csv(REF / "research" / "TAPG_event_study.csv")
    ev["surprise_proxy_yoy"] = ev.event.map(SURPRISE_PROXY)
    rho = ev.surprise_proxy_yoy.rank().corr(ev.car_peers_0_1.rank())
    sd1 = ev.car_peers_0_1.std()
    mean1 = ev.car_peers_0_1.mean()
    md = ["# TAPG — Tactical Q4-Beat Test and Entry-Price Range (Phase IV)", "",
          "_Generated by `valuation/tapg_entry_and_tactical.py`. Event data: `TAPG_event_study.csv` (A-022). Scenario inputs are EST (A-028). No rating._", "",
          "## (a) Do earnings beats move TAPG? (results filings 2025–26, n = 8)", "",
          "| Event | YoY profit growth (surprise proxy) | CAR vs peers [0,1] | CAR vs peers [0,5] |", "|---|---|---|---|"]
    md += [f"| {r.event} | {r.surprise_proxy_yoy:+.0%} | {r.car_peers_0_1:+.1%} | {r.car_peers_0_5:+.1%} |" for r in ev.itertuples()]
    md += ["", f"- Rank correlation (surprise proxy vs CAR [0,1]): **{rho:+.2f}** (n = 8). Mean CAR [0,1] {mean1:+.1%}, standard deviation {sd1:.1%}.",
           "- The one event with a known consensus beat (9M26: 85% of FY consensus by Q3) produced CAR [0,1] of −0.7% vs peers.",
           "- **Conclusion:** there is no evidence that TAPG results surprises produce a predictable short-term reaction.",
           "  - A Q4 beat (filing expected by about 31 Mar 2027) would be a coin-flip trade with about ±5% noise per event.",
           "  - It would carry 4 months of exposure to FY27 risk while waiting.",
           "  - **A tactical trade is not supported.** n = 8; a real consensus-surprise history is not available PIT."]
    # (b) entry range
    rows = []
    for lab, e, p, d in SCEN:
        v = value_per_share(e)
        rows.append({"scenario": lab, "sustainable_np": e, "prob": p, "value_per_share": v, "div_12m": d})
    S = pd.DataFrame(rows)
    ev_value = (S.prob * (S.value_per_share + S.div_12m)).sum()
    exp_ret = ev_value / PRICE - 1
    entry = ev_value / (1 + HURDLE)
    entry_ke = ev_value / (1 + KE)
    downside = (S.iloc[0].value_per_share + S.iloc[0].div_12m) / PRICE - 1
    upside = (S.iloc[2].value_per_share + S.iloc[2].div_12m) / PRICE - 1
    md += ["", "## (b) Attractive entry-price range", "",
           f"Value per share = E × {CONV} × (1+{G:.0%}) / ({KE:.1%} − {G:.0%}) / {SHARES:,.0f}mn shares.", "",
           "| Scenario | Sustainable profit (IDR bn) | Probability (EST) | Value/share | + 12m dividend | Total vs IDR 1,710 |", "|---|---|---|---|---|---|"]
    md += [f"| {r.scenario} | {r.sustainable_np:,.0f} | {r.prob:.0%} | {r.value_per_share:,.0f} | {r.div_12m:,.0f} | {(r.value_per_share + r.div_12m) / PRICE - 1:+.0%} |" for r in S.itertuples()]
    md += ["", f"- **Probability-weighted 12-month value** (incl. dividends): IDR {ev_value:,.0f}, i.e. expected total return **{exp_ret:+.1%}** at IDR 1,710. Downside case {downside:+.0%}, upside case {upside:+.0%}.",
           f"- **Entry range:**",
           f"  - IDR {entry:,.0f} for a {HURDLE:.1%} hurdle (ke + 5pp margin of safety).",
           f"  - IDR {entry_ke:,.0f} for a bare {KE:.1%} cost of equity.",
           "  - **Attractive below about IDR "
           f"{entry:,.0f}; fair around {entry_ke:,.0f}–{ev_value:,.0f}.**",
           f"- **Dividend capacity:** at IDR {entry:,.0f}, the base forward 12-month dividend (IDR {S.div_12m.iloc[1]:,.0f}) yields {S.div_12m.iloc[1] / entry:.1%}. Coverage: FY25 free cash flow 2,809bn + JV cash dividends 959bn vs 3,276bn paid.",
           "- **Sensitivity:**",
           f"  - Moving 10pp of probability from base to bear lowers the value by about IDR {(0.1 * ((value_per_share(4062) + 200) - (value_per_share(2810) + 160))):,.0f}.",
           f"  - ke ±1pp moves it by about ∓9%.",
           "  - The probabilities are judgemental and not estimated."]
    # Uncertainty in the scenario probabilities (Phase V, D-024): Dirichlet around the 30/50/20 weights
    rng = np.random.default_rng(20261124)
    W = rng.dirichlet(np.array([0.30, 0.50, 0.20]) * 10.0, 20000)  # concentration 10 = weak confidence
    tot = (S.value_per_share + S.div_12m).to_numpy()
    er = W @ tot / PRICE - 1
    pq = np.percentile(er, [5, 50, 95])
    md += ["", "## Probability uncertainty (Dirichlet, concentration 10 around 30/50/20)", "",
           f"- Expected 12-month return: median {pq[1]:+.1%}, 5–95% range {pq[0]:+.1%} to {pq[2]:+.1%}.",
           f"- P(expected return > ke {KE:.1%}) = {(er > KE).mean():.0%}; P(> hurdle {HURDLE:.1%}) = {(er > HURDLE).mean():.0%}.",
           "- Even with generous weight uncertainty, the expected return rarely clears the hurdle at this price.",
           f"- **Forward dividend capacity** (payout {PAYOUT:.0%}, interims ≈ {INTERIM_SHARE:.0%} of the annual payout): next-12-month dividends of IDR "
           + " / ".join(f"{d:,.0f}" for d in S.div_12m) + " (bear / base / bull), replacing the earlier trailing-yield inputs (160 / 200 / 230)."]
    out = REF / "research"
    S.to_csv(out / "TAPG_entry_scenarios.csv", index=False, float_format="%.1f")
    ev.to_csv(out / "TAPG_event_surprise_proxy.csv", index=False, float_format="%.4f")
    pd.Series({"prob_uncertainty_p05": pq[0], "prob_uncertainty_p50": pq[1], "prob_uncertainty_p95": pq[2],
               "p_exceeds_hurdle": float((er > HURDLE).mean()), "expected_value_12m": ev_value, "expected_return_at_1710": exp_ret, "entry_price_hurdle": entry,
               "entry_price_ke": entry_ke, "rank_corr_surprise_car01": rho, "car01_sd": sd1}).to_csv(out / "TAPG_entry_summary.csv")
    (ROOT / "research" / "company" / "TAPG" / "tactical_and_entry.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
