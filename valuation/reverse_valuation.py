"""Reverse valuation: what sustainable earnings does TAPG's share price imply? (Phase III, P4)

Equity-level, no-growth-to-moderate-growth perpetuity on distributable earnings:
    Market cap = E_norm x conversion x (1 + g) / (ke - g)
where conversion = the share of profit available to shareholders after maintenance
capex (FCFE / NP). Solve for E_norm on a grid of ke, g and conversion (all EST,
documented in A-024). TAPG is in net cash; JV value is inside E (equity-method share).

Compared with: consensus FY26/FY27 (S&P), our FY26/FY27 scenarios, and historical
profit (FY2021-25 reported; CPO-price regimes differ).

Inputs (OBS unless stated): price 1,710 (S-002, 2026-11-24); shares 19,852.54mn (9M26 FS,
via Astra S-025 citation, matches Yahoo); cash 1,937bn and total debt 964.5bn at Sep-26
(9M26 FS / S-020).
Output: research/company/TAPG/reverse_valuation.md, data/reference/research/TAPG_reverse_valuation.csv
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
REF = ROOT / "data" / "reference"
PRICE, SHARES = 1710.0, 19852.54  # IDR, mn shares
MCAP = PRICE * SHARES / 1000  # IDR bn
NET_CASH = 1937.0 - 964.5
KE = [0.11, 0.12, 0.13, 0.14]
G = [0.0, 0.02, 0.04]
CONV = [0.80, 0.90]


def implied_e(ke: float, g: float, conv: float, mcap: float = MCAP) -> float:
    return mcap * (ke - g) / ((1 + g) * conv)


def main() -> int:
    rows = [{"ke": ke, "g": g, "fcfe_conversion": c, "implied_normalised_np": implied_e(ke, g, c)}
            for ke in KE for g in G for c in CONV]
    R = pd.DataFrame(rows)
    R.to_csv(REF / "research" / "TAPG_reverse_valuation.csv", index=False, float_format="%.1f")
    hist = {2021: 1159.0, 2022: 2981.1, 2023: 1608.2, 2024: 3120.3, 2025: 3702.3}
    fy27 = pd.read_csv(REF / "research" / "TAPG_fy2027_quarterly.csv").groupby("scenario").net_profit_owners.sum()
    central = implied_e(0.125, 0.02, 0.85)
    md = ["# TAPG — Reverse Valuation (what is priced in?)", "",
          "_Generated by `valuation/reverse_valuation.py`. Equity perpetuity: market cap = E × conversion × (1+g)/(ke−g). Assumptions A-024 (EST). No target price, no rating._", "",
          f"Market cap at IDR {PRICE:,.0f} = **IDR {MCAP:,.0f}bn**; net cash about {NET_CASH:,.0f}bn (Sep-26).", "",
          "## Implied sustainable net profit (IDR bn)", "", "| ke | g | conversion 0.80 | conversion 0.90 |", "|---|---|---|---|"]
    for ke in KE:
        for g in G:
            a = R[(R.ke == ke) & (R.g == g) & (R.fcfe_conversion == 0.8)].implied_normalised_np.iloc[0]
            b = R[(R.ke == ke) & (R.g == g) & (R.fcfe_conversion == 0.9)].implied_normalised_np.iloc[0]
            md.append(f"| {ke:.0%} | {g:.0%} | {a:,.0f} | {b:,.0f} |")
    md += ["", f"Central case (ke 12.5%, g 2%, conversion 0.85): **implied sustainable net profit ≈ {central:,.0f}bn**.", "",
           "## Comparison", "", "| Reference | Net profit (IDR bn) | vs implied central |", "|---|---|---|"]
    refs = [("Reported FY2021", hist[2021]), ("Reported FY2022 (price spike)", hist[2022]), ("Reported FY2023 (price trough)", hist[2023]),
            ("Reported FY2024", hist[2024]), ("Reported FY2025", hist[2025]), ("Average FY2021–25", sum(hist.values()) / 5),
            ("Average FY2023–25", (hist[2023] + hist[2024] + hist[2025]) / 3),
            ("Consensus FY26 (S&P)", 4220.0), ("Consensus FY27 (S&P)", 225.305 * SHARES / 1000),
            ("Our FY26 base", 4714.7), ("Our FY27 bear", fy27["bear"]), ("Our FY27 base", fy27["base"]), ("Our FY27 bull", fy27["bull"])]
    md += [f"| {n} | {v:,.0f} | {v / central - 1:+.0%} |" for n, v in refs]
    md += ["", "## Reading", "",
           f"- The price implies sustainable net profit of about **{central:,.0f}bn** in the central case; the grid range is about 2.5–5.9tn.",
           "- That is roughly consensus FY26 (4.2tn), roughly our FY27 base (4.1tn), about 10% above FY2025 (3.7tn), and about 46% above the FY2023–25 average (2.8tn).",
           "- **The market is NOT pricing TAPG on mid-cycle profit.** It is already capitalising roughly the current high level of earnings as sustainable.",
           "- **Upside** therefore needs earnings to stay above about 4.1tn for longer than the market assumes (our FY27 bull, 5.0tn, is about +21%) or a lower discount rate.",
           "- **Downside:** if profit mean-reverts toward the FY2023–25 average, the implied value falls about 30% or more. A one-quarter FY26 beat barely changes normalised value.",
           "- **Each 1pp of ke** moves implied earnings by about 8–9%.",
           "- **Limitations:**",
           "  - Single-stage perpetuity.",
           "  - Assumed conversion.",
           "  - The CPO cycle is not modelled explicitly.",
           "  - No separate value for the land bank or USTP beyond earnings (see `valuation/ustp_module.py`)."]
    (ROOT / "research" / "company" / "TAPG" / "reverse_valuation.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
